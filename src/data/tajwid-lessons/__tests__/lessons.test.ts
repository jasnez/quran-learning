/**
 * The lesson text comes from the reviewed lesson doc (2026-11). Quranic text and transcription are
 * never typed into the lessons: examples are references into src/data/ayahs, and any transcription
 * quoted next to an ayah reference must be in that ayah.
 */
import { describe, it, expect } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getAllTajwidLessons, type LessonBlock, type TajwidLesson } from "../index";
import { resolveLessonExample } from "@/lib/quran/lessonExample";
import type { TajwidSegment } from "@/types/quran";

const AYAHS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "../../ayahs");
const files = readdirSync(AYAHS_DIR);
type AyahData = { ayahNumber: number; arabicText: string; transliteration: string; tajwidSegments: TajwidSegment[] };

function ayah(surah: number, n: number): AyahData {
  const file = files.find((f) => f.startsWith(`${String(surah).padStart(3, "0")}-`));
  if (!file) throw new Error(`no data for surah ${surah}`);
  const found = (JSON.parse(readFileSync(path.join(AYAHS_DIR, file), "utf-8")).ayahs as AyahData[]).find(
    (a) => a.ayahNumber === n,
  );
  if (!found) throw new Error(`no ayah ${surah}:${n}`);
  return found;
}

function blocksOf(lesson: TajwidLesson): LessonBlock[] {
  return lesson.sections.flatMap((s) => s.blocks);
}

/** Every text a reader sees in a lesson, examples' notes excluded (they are checked against their own ayah). */
function texts(lesson: TajwidLesson): string[] {
  const out = [lesson.title, lesson.subtitle, lesson.summary, ...lesson.sections.map((s) => s.heading)];
  for (const b of blocksOf(lesson)) {
    if (b.kind === "p") out.push(b.lead ?? "", b.text);
    if (b.kind === "list") for (const i of b.items) out.push(typeof i === "string" ? i : `${i.lead} ${i.text}`);
    if (b.kind === "table") out.push(...b.columns, ...b.rows.flat());
  }
  for (const q of lesson.quiz) out.push(q.question, q.explanation, ...q.options);
  return out;
}

describe("tajwid lessons", () => {
  it("keep their ids, slugs and rules, with the reviewed titles", async () => {
    const lessons = await getAllTajwidLessons();
    expect(lessons.map((l) => [l.id, l.slug, l.ruleType, l.title])).toEqual([
      [1, "uvod-tajwid", "normal", "Uvod u tedžvid"],
      [2, "mad-duljenje", "mad", "Medd: dužina vokala"],
      [3, "ghunnah-nazalni-zvuk", "ghunnah", "Gunne: glas kroz nos"],
      [4, "ikhfa-skriveni-zvuk", "ikhfa", "Ihfa: prikriven nūn"],
      [5, "qalqalah-odskok", "qalqalah", "Kalkala: odskok glasa"],
    ]);
  });

  it("every example resolves inside its ayah: Arabic and transcription are substrings, colors fit, link is right", async () => {
    for (const lesson of await getAllTajwidLessons()) {
      const examples = blocksOf(lesson).flatMap((b) => (b.kind === "examples" ? b.examples : []));
      expect(examples.length, lesson.slug).toBeGreaterThan(0);
      for (const ex of examples) {
        const data = ayah(ex.surah, ex.ayah);
        const r = resolveLessonExample(ex, data);
        const where = `${lesson.slug} ${ex.surah}:${ex.ayah}`;
        expect(data.arabicText.includes(r.arabic), where).toBe(true);
        expect(data.transliteration.includes(r.transliteration), where).toBe(true);
        expect(r.segments.map((s) => s.text).join(""), where).toBe(r.arabic);
        expect(r.href, where).toBe(`/surah/${ex.surah}?ayah=${ex.ayah}`);
        for (const [, quote] of ex.note.matchAll(/„([^“]+)“/g)) {
          expect(data.transliteration.includes(quote), `${where} note quotes „${quote}“`).toBe(true);
        }
      }
    }
  });

  // A range one word off still resolves inside the ayah, so the substring checks above pass. The
  // snapshot (generated by Vitest from the data, never typed) pins each example's fragment; a changed
  // range or changed ayah data shows up as a snapshot diff in review. Checked against the reviewed
  // lesson doc on 2026-11-23.
  it("each example shows the fragment the reviewed doc shows", async () => {
    const rows: string[] = [];
    for (const lesson of await getAllTajwidLessons()) {
      for (const ex of blocksOf(lesson).flatMap((b) => (b.kind === "examples" ? b.examples : []))) {
        const r = resolveLessonExample(ex, ayah(ex.surah, ex.ayah));
        const colored = [...new Set(r.segments.filter((s) => s.rule !== "normal").map((s) => s.rule))].join(",");
        rows.push(`${lesson.id} ${ex.surah}:${ex.ayah} | ${r.arabic} | ${r.transliteration} | ${colored || "-"}`);
      }
    }
    expect(rows).toMatchSnapshot();
  });

  it("a transcription quoted next to an ayah reference is in that ayah", async () => {
    let checked = 0;
    for (const lesson of await getAllTajwidLessons()) {
      for (const t of texts(lesson)) {
        const refs = [
          ...[...t.matchAll(/„([^“]+)“ \((\d+):(\d+)\)/g)].map((m) => [m[1], m[2], m[3]]),
          ...[...t.matchAll(/(\d+):(\d+) \(„([^“]+)“\)/g)].map((m) => [m[3], m[1], m[2]]),
        ];
        for (const [quote, s, a] of refs) {
          expect(ayah(Number(s), Number(a)).transliteration.includes(quote), `${lesson.slug}: „${quote}“ ${s}:${a}`).toBe(true);
          checked++;
        }
      }
    }
    expect(checked).toBeGreaterThanOrEqual(6);
  });

  it("every quiz question has four options, one right answer and an explanation", async () => {
    for (const lesson of await getAllTajwidLessons()) {
      expect(lesson.quiz.length, lesson.slug).toBeGreaterThanOrEqual(3);
      for (const q of lesson.quiz) {
        expect(q.options, q.question).toHaveLength(4);
        expect(q.correctIndex, q.question).toBeGreaterThanOrEqual(0);
        expect(q.correctIndex, q.question).toBeLessThan(4);
        expect(q.explanation.length, q.question).toBeGreaterThan(0);
      }
    }
  });
});
